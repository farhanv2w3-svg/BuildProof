/**
 * Windows-only workaround (run via `npm run postinstall`):
 * On some machines, local Application Control policy silently blocks loading
 * unsigned native .node modules in node_modules (rollup's native parser) — and
 * also blocks `.mjs` scripts. When the native binding is blocked we rewrite
 * rollup's loader to use the official WebAssembly build (@rollup/wasm-node).
 * On normal machines/CI this script does nothing.
 */
const fs = require("node:fs");
const path = require("node:path");

const HERE = __dirname;
const SHIM = `// Auto-generated by scripts/patch-rollup-wasm.cjs
// Local security policy blocks the unsigned native rollup module on this
// machine; use the official WebAssembly build instead (same package version).
module.exports = require('@rollup/wasm-node/dist/native.js');
`;

const nativePath = path.join(HERE, "..", "node_modules", "rollup", "dist", "native.js");
if (!fs.existsSync(nativePath)) {
  console.log("[patch-rollup-wasm] rollup not installed yet — skipping");
  process.exit(0);
}

let nativeWorks = false;
try {
  require(path.join(HERE, "..", "node_modules", "@rollup", "rollup-win32-x64-msvc"));
  nativeWorks = true;
} catch {
  nativeWorks = false;
}

if (nativeWorks) {
  console.log("[patch-rollup-wasm] native rollup binding loads fine — no patch needed");
  process.exit(0);
}

fs.writeFileSync(nativePath, SHIM);
console.log(
  "[patch-rollup-wasm] Native rollup binding BLOCKED by local policy — patched rollup to use @rollup/wasm-node."
);
